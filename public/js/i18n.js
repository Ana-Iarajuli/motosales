const DICTS = { en, ka };

// ?lang=ka in a link switches language (and is remembered), so translated pages can be shared
const stored = (() => {
  const fromUrl = new URLSearchParams(location.search).get('lang');
  try {
    if (DICTS[fromUrl]) localStorage.setItem('lang', fromUrl);
    return localStorage.getItem('lang');
  } catch {
    return fromUrl;
  }
})();
export const lang = DICTS[stored] ? stored : navigator.language?.toLowerCase().startsWith('ka') ? 'ka' : 'en';
document.documentElement.lang = lang;

export function setLang(id) {
  try {
    localStorage.setItem('lang', id);
  } catch {}
  location.reload(); // every page renders its text once, so a reload is the simplest full switch
}

function lookup(key) {
  return DICTS[lang][key] ?? en[key];
}

export function t(key, vars) {
  let s;
  if (vars && typeof vars.n === 'number') {
    const form = vars.n === 1 ? '_one' : '_other';
    s = DICTS[lang][key + form] ?? DICTS[lang][key + '_other'] ?? en[key + form];
  }
  s ??= lookup(key) ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? (k === 'n' ? vars.n.toLocaleString() : vars[k]) : m)) : s;
}

/** Translated label for a data value such as a category ('cat') or gender. */
export const tv = (prefix, value) => lookup(`${prefix}.${value}`) ?? value;

/** Translates static markup: data-i18n (text), data-i18n-placeholder, -aria-label, -title. */
export function applyI18n(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const attr of ['placeholder', 'aria-label', 'title']) {
    const data = `i18n${attr.replace(/(^|-)(\w)/g, (m, d, c) => c.toUpperCase())}`; // aria-label -> i18nAriaLabel
    for (const el of root.querySelectorAll(`[data-i18n-${attr}]`)) el.setAttribute(attr, t(el.dataset[data]));
  }
}
